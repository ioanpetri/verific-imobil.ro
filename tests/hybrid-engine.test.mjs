import assert from 'node:assert/strict';
import {calibrateCriteria,guardMarketScores,calibrationReport} from '../app/lib/hybrid-engine.js';
const criteria={layout:{score:8,basis:'Date din anunt',subcriteria:{area:{score:8},distribution:{score:9},bathrooms:{score:8},kitchen:{score:8}}},visual:{score:8,basis:'Date din anunt',subcriteria:{orientation:{score:8},windows:{score:8},obstructions:{score:9},view:{score:8}}},materials:{score:8,basis:'Date din anunt',subcriteria:{quality:{score:8},workmanship:{score:8},design:{score:8},condition:{score:8}}}};
const notes=calibrateCriteria(criteria,'Apartament semidecomandat la parter, finisaje uzate');
assert.equal(criteria.layout.subcriteria.distribution.score,6.5);
assert.equal(criteria.visual.subcriteria.obstructions.score,7);
assert.equal(criteria.materials.subcriteria.condition.score,5);
assert.equal(notes.length,3);
const acquisition={subscores:{priceValue:9,buyerDemand:7,compromises:6,resale:7}};
const investment={subscores:{netYield:9,appreciation:9,liquidity:7,entryRisk:9}};
guardMarketScores(acquisition,investment,'160000 EUR, 45 mp');
assert.equal(acquisition.subscores.priceValue,5);
assert.equal(investment.subscores.netYield,5);
assert.equal(investment.subscores.appreciation,5);
assert.equal(investment.subscores.entryRisk,5);
assert.equal(investment.score,5.5);
const reports=calibrationReport({structural:15,layout:15,thermal:12,acoustic:10,visual:10,materials:10,liveability:10,neighbourhood:18});
assert.equal(reports.length,3);
console.log('PASS: guardrails, neutralitate financiara, 3 cazuri:',reports);
