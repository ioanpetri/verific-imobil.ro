import assert from 'node:assert/strict';
import {evaluateLayoutScreening} from '../app/lib/layout-v37.js';
const test=(text,facts={})=>evaluateLayoutScreening({text,facts});
const a=test('Apartament 3 camere decomandat, suprafata utila 68 mp, 1 baie, bucatarie 8 mp, debara, boxa.',{bedrooms:2,bedroomAreas:[13,9.5],livingArea:19,separateDayNight:true,storageConfirmedAbsent:false});
assert.ok(a.score>=7&&a.score<=9.5,JSON.stringify(a));
assert.equal(a.subscores.B,9.5);
assert.ok(a.confidence>=.4);
const no=test('Apartament frumos, renovat complet.');
assert.equal(no.score,null);
assert.equal(no.class,'Date insuficiente');
const veto=test('Apartament 2 camere decomandat, suprafata utila 50 mp, 1 baie, bucatarie 8 mp.',{bedroomWithoutWindow:true});
assert.ok(veto.score<=5);
assert.ok(veto.veto.some(v=>v.code==='V1'));
const bath=test('Apartament 2 camere decomandat, suprafata utila 50 mp, 0 bai, bucatarie 8 mp.',{bathrooms:0});
assert.ok(bath.score<=3);
const sem=test('Apartament 2 camere semidecomandat, suprafata utila 50 mp, 1 baie, bucatarie 8 mp.');
assert.equal(sem.subscores.B,7);
const de=test('Apartament 2 camere decomandat, suprafata utila 50 mp, 1 baie, bucatarie 8 mp.');
assert.equal(de.subscores.B,9);
const missingKitchen=test('Apartament 2 camere decomandat, suprafata utila 50 mp, 1 baie.');
assert.ok(missingKitchen.missing.includes('Suprafata bucatariei'));
console.log('layout-v37: 7 verificari OK');
